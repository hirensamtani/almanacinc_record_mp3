// swift-tools-version: 5.9
import PackageDescription

// Swift Package Manager manifest for the almanacinc_record_mp3 Flutter plugin.
//
// NOTE ON THE TWO-TARGET SPLIT
// ────────────────────────────
// Swift Package Manager does NOT allow a single target to mix Swift and C
// sources. The plugin therefore ships two targets:
//
//   • almanac_lame            — the C encoder: the AlmanacLame wrapper plus the
//                               vendored LAME 3.100 sources. Only AlmanacLame.h
//                               (in include/) is public; the lame/ headers stay
//                               private to the target.
//   • almanacinc_record_mp3   — the Swift plugin. It depends on almanac_lame for
//                               the AlmanacLame* functions and on FlutterFramework
//                               for `import Flutter`.
//
// CocoaPods (the .podspec) keeps a single mixed-language pod — CocoaPods, unlike
// SPM, permits Swift + C in one module — and points at the same Sources tree.

let package = Package(
    name: "almanacinc_record_mp3",
    platforms: [
        .iOS("12.0")
    ],
    products: [
        // Library name must use "-"; target names keep "_".
        .library(
            name: "almanacinc-record-mp3",
            targets: ["almanacinc_record_mp3"]
        )
    ],
    dependencies: [
        // Generated by the Flutter tool (Flutter >= 3.41); vends `import Flutter`.
        .package(name: "FlutterFramework", path: "../FlutterFramework")
    ],
    targets: [
        // ── C target: AlmanacLame wrapper + vendored LAME 3.100 ───────────────
        .target(
            name: "almanac_lame",
            path: "Sources/almanac_lame",
            // Only headers under include/ are exposed to the Swift module.
            publicHeadersPath: "include",
            cSettings: [
                // #include "lame.h"   → Sources/almanac_lame/lame/include/lame.h
                .headerSearchPath("lame/include"),
                // #include "config.h" → Sources/almanac_lame/lame/config.h
                .headerSearchPath("lame"),
                // Vendored LAME reads our hand-written config.h behind this gate.
                .define("HAVE_CONFIG_H", to: "1"),
                // Silence the (expected) warnings from the vendored LAME sources.
                .unsafeFlags(["-w"])
            ]
        ),
        // ── Swift target: the Flutter plugin ──────────────────────────────────
        .target(
            name: "almanacinc_record_mp3",
            dependencies: [
                "almanac_lame",
                .product(name: "FlutterFramework", package: "FlutterFramework")
            ],
            path: "Sources/almanacinc_record_mp3",
            resources: [
                // iOS 17+ App Store privacy manifest.
                .process("PrivacyInfo.xcprivacy")
            ]
        )
    ]
)
